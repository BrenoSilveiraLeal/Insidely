export type GeneratedProfessional = {
  index: number;
  name: string;
  email: string;
  companySlug: string;
  professionSlug: string;
  title: string;
  area: string;
  location: string;
  region: string;
  yearsExperience: number;
  privacyMode: "PUBLIC" | "PROTECTED" | "PSEUDONYM";
  pseudonym: string | null;
  workMode: "REMOTE" | "HYBRID" | "ONSITE";
  seniority: "JUNIOR" | "MID" | "SENIOR" | "LEAD" | "MANAGER";
};

export function generateProfessionals(total = 80): GeneratedProfessional[] {
  return Array.from({ length: total }, (_, index) => {
    const first = firstNames[index % firstNames.length];
    const last = lastNames[Math.floor(index / firstNames.length) % lastNames.length];
    const company = companySeed[(index * 7 + (index % 3)) % companySeed.length];
    const profession = professionSeed[(index * 5 + (index % 4)) % professionSeed.length];
    const categoryKey = profession[2].toLocaleLowerCase("pt-BR");
    const titles = titlesByProfession[categoryKey] ?? [profession[1]];
    const privacyMode = index % 5 === 0 ? "PUBLIC" : index % 3 === 0 ? "PSEUDONYM" : "PROTECTED";
    return {
      index,
      name: `${first} ${last}`,
      email: index === 0 ? "consultor@insidely.com" : `profissional${String(index + 1).padStart(2, "0")}@insidely.demo`,
      companySlug: company[0],
      professionSlug: profession[0],
      title: titles[index % titles.length],
      area: profession[2],
      location: cities[index % cities.length][0],
      region: cities[index % cities.length][1],
      yearsExperience: 1 + (index % 12),
      privacyMode,
      pseudonym: privacyMode === "PSEUDONYM" ? `${first.charAt(0)}. Profissional #${1800 + index}` : null,
      workMode: (["REMOTE", "HYBRID", "ONSITE"] as const)[index % 3],
      seniority: (["JUNIOR", "MID", "SENIOR", "LEAD", "MANAGER"] as const)[index % 5],
    };
  });
}
